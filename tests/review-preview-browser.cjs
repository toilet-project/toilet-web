// Interactive isolated preview only. No production origin, credentials or API fixtures.
const assert = require('node:assert/strict')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_PACKAGE || 'playwright')
const origin = process.env.REVIEW_PREVIEW_ORIGIN || 'http://127.0.0.1:4187'
assert.ok(['http://127.0.0.1:4187', 'https://preview.geupddong.com'].includes(origin))
const output = process.env.REVIEW_SCREENSHOT_DIR || path.resolve('.tmp-review-screenshots')
const fs = require('node:fs')
fs.mkdirSync(output, { recursive: true })
const visible = async locator => assert.equal(await locator.isVisible(), true)
;(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
    const page = await context.newPage()
    const writes = [], errors = []
    page.on('request', r => { if (!['GET', 'HEAD'].includes(r.method())) { const u = new URL(r.url()); writes.push({ method: r.method(), origin: u.origin, path: u.pathname }) } })
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(origin + '/review-preview', { waitUntil: 'networkidle' })
    await page.screenshot({ path: path.join(output, 'review-card-mobile.png'), fullPage: true })
    const open = async () => {
      await page.getByRole('button', { name: '리뷰', exact: true }).click()
      const intro = page.getByRole('button', { name: '확인하고 리뷰 쓰기' })
      if (await intro.isVisible()) await intro.click()
    }
    const fill = async () => {
      await page.getByRole('radio', { name: '만족도 4점' }).check()
      await page.getByRole('radio', { name: '청결도 5점' }).check()
      await page.getByRole('button', { name: '있었어요', exact: true }).click()
    }
    await page.getByText('프리뷰 시나리오 설정', { exact: true }).click()
    await page.getByLabel('위치 확인 결과').selectOption('far')
    await page.getByRole('button', { name: '리뷰', exact: true }).click()
    await visible(page.getByRole('status').getByText(/150m 안/))
    assert.equal(await page.getByRole('dialog').count(), 0)
    await page.getByLabel('위치 확인 결과').selectOption('near')
    await open()
    await page.getByRole('button', { name: '리뷰 남기기', exact: true }).click()
    await visible(page.getByRole('dialog').getByRole('alert'))
    await fill()
    const slider = page.getByRole('slider', { name: '대기시간' })
    assert.equal(await slider.inputValue(), '0')
    await slider.focus(); await slider.press('End')
    assert.equal(await slider.getAttribute('aria-valuetext'), '1시간 이상')
    await page.getByLabel('한 줄 더 남겨주세요', { exact: false }).fill('🙂'.repeat(201))
    assert.equal(Array.from(await page.locator('textarea').inputValue()).length, 200)
    await page.locator('textarea').fill('디자인 체험 리뷰예요. 깨끗하고 휴지가 넉넉했어요.')
    await page.locator('.rv-dialog-body').evaluate(el => { el.scrollTop = 0 })
    await page.screenshot({ path: path.join(output, 'review-form-mobile.png') })
    await page.getByRole('button', { name: '리뷰 남기기', exact: true }).click()
    await page.getByRole('button', { name: '내 리뷰 보기', exact: true }).click()
    await page.getByRole('button', { name: /월드컵경기장역/ }).click()
    await page.getByRole('button', { name: '수정하기', exact: true }).click()
    await page.locator('textarea').fill('수정된 체험 리뷰입니다.')
    await page.getByRole('button', { name: '수정한 내용 저장', exact: true }).click()
    await page.getByRole('button', { name: '내 리뷰 보기', exact: true }).click()
    await visible(page.getByText('수정된 체험 리뷰입니다.', { exact: true }))
    await page.getByLabel('프리뷰: 작성 후 7일 경과 시험').check()
    await page.getByRole('button', { name: /월드컵경기장역/ }).click()
    assert.equal(await page.getByRole('button', { name: '수정하기', exact: true }).count(), 0)
    await page.getByRole('button', { name: '닫기', exact: true }).click()
    await page.getByLabel('프리뷰: 작성 후 7일 경과 시험').uncheck()
    await page.getByRole('button', { name: /월드컵경기장역/ }).click()
    await page.getByRole('button', { name: '작성자 정보 지우기', exact: true }).click()
    await visible(page.getByText('급똥 회원 탈퇴는 아닙니다.', { exact: true }))
    await page.screenshot({ path: path.join(output, 'review-remove-mobile.png') })
    await page.getByRole('button', { name: '정보 지우기', exact: true }).click()
    await visible(page.getByText('첫 리뷰를 기다리고 있어요', { exact: true }))
    await page.getByRole('button', { name: '화장실 카드로', exact: true }).click()
    await visible(page.getByText('익명', { exact: true }))
    await visible(page.getByText('수정된 체험 리뷰입니다.', { exact: true }))
    await page.getByText('프리뷰 시나리오 설정', { exact: true }).click()
    await page.getByLabel('저장 실패 시험').check()
    await open(); await fill()
    await page.getByRole('button', { name: '리뷰 남기기', exact: true }).click()
    await visible(page.getByRole('dialog').getByRole('alert'))
    assert.equal(await page.getByRole('radio', { name: '만족도 4점' }).isChecked(), true)
    await page.getByRole('button', { name: '닫기', exact: true }).click()
    await page.getByRole('button', { name: '그만두기', exact: true }).click()
    await page.getByRole('button', { name: '테스트 로그아웃', exact: true }).click()
    await page.getByRole('button', { name: '리뷰', exact: true }).click()
    await visible(page.getByRole('dialog', { name: '로그인 · 간편가입', exact: true }))
    await page.getByRole('button', { name: '닫기', exact: true }).click()
    await page.reload({ waitUntil: 'networkidle' })
    assert.equal(await page.getByText('익명', { exact: true }).count(), 0)
    await context.close()
    for (const width of [320, 390, 1280]) {
      const ctx = await browser.newContext({ viewport: { width, height: width > 600 ? 1000 : 844 } })
      const p = await ctx.newPage()
      await p.goto(origin + '/review-preview', { waitUntil: 'networkidle' })
      assert.equal(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `page overflow ${width}`)
      if (width === 1280) await p.screenshot({ path: path.join(output, 'review-card-desktop.png'), fullPage: true })
      await p.getByRole('button', { name: '리뷰', exact: true }).click()
      await p.getByRole('button', { name: '확인하고 리뷰 쓰기' }).click()
      assert.equal(await p.locator('.rv-dialog').evaluate(el => el.scrollWidth <= el.clientWidth), true, `dialog overflow ${width}`)
      assert.equal(await p.locator('.rv-dialog-body').evaluate(el => el.scrollWidth <= el.clientWidth), true, `body overflow ${width}`)
      await p.screenshot({ path: path.join(output, `review-form-${width}.png`) })
      await ctx.close()
    }
    // Cloudflare's existing same-origin RUM beacon is infrastructure telemetry,
    // not a review mutation. Do not permit any other POST or API write.
    const infrastructureBeacons = writes.filter(r => r.method === 'POST' && r.origin === 'https://preview.geupddong.com' && r.path === '/cdn-cgi/rum')
    assert.deepEqual(writes.filter(r => !infrastructureBeacons.includes(r)), [], 'preview must never submit review/member writes')
    assert.deepEqual(errors, [])
    console.log(`REVIEW_PREVIEW_PASS create/edit/detach/retention/7day/150m/failure/login/reset/320/390/1280; no review/member writes; existing RUM beacons=${infrastructureBeacons.length}`)
  } finally { await browser.close() }
})().catch(e => { console.error(e); process.exitCode = 1 })
