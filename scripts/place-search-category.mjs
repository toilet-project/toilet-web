export function placeSearchCategory(place) {
  const source = (place.classification?.labels ?? []).join(' ').toLocaleLowerCase('en-US')
  const detail = rules.find(([, pattern]) => pattern.test(source))?.[0]
  const code = detail ?? (labels[place.category] ? place.category : 'unknown')
  return { code, ...labels[code] }
}

