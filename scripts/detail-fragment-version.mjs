import {createHash} from 'node:crypto'
import {readFile,writeFile} from 'node:fs/promises'
const source=await readFile(new URL('../src/server/detailFragmentTemplate.ts',import.meta.url),'utf8')
const version=createHash('sha256').update(source.replaceAll('\r\n','\n')).digest('hex').slice(0,24)
const output=`// Generated by scripts/detail-fragment-version.mjs; excludes site chrome and build IDs.\nexport const DETAIL_FRAGMENT_TEMPLATE = '${version}'\n`
const target=new URL('../src/server/detailFragmentVersion.ts',import.meta.url)
if(process.argv.includes('--check')){
  if(await readFile(target,'utf8')!==output)throw Error('Run node scripts/detail-fragment-version.mjs after changing the fragment template')
}else await writeFile(target,output)
